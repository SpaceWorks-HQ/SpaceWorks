POLICIES = {
    name: SettingPolicy(
        Policy.EXACT_FINGERPRINT if name in EXACT else
        Policy.CAPABILITY_PROBE if name in CAPABILITY else
        Policy.VALUE_COMPARISON if name in VALUE else Policy.EXCLUDED,
        secret_bearing=name in EXACT or name in {
            "AWS_SECRET_ACCESS_KEY", "EMAIL_HOST_PASSWORD", "CELERY_BROKER_URL",
            "CELERY_RESULT_BACKEND", "DATABASE_URL", "SPACEWORKS_RUNTIME_DATABASE_URL",
            "BACKUP_ARCHIVE_SIGNING_PRIVATE_KEY",
        },
        blocks_restore=name in EXACT or name in CAPABILITY or name in BLOCKING_VALUE,
    )
    for name in ENV_SURFACE
}


def assert_complete(env_names):
    missing = set(env_names) - set(POLICIES)
    stale = set(POLICIES) - set(env_names)
    if missing or stale:
        raise AssertionError(f"backup setting policies drifted: missing={sorted(missing)}, stale={sorted(stale)}")
